# Outbound WhatsApp messages per organization, local month (Santo Domingo) and how they went
# out: an approved template, or a session message inside the 24-hour window. Since October 2026
# Meta charges both, so this feeds the pricing of the plans. Internal: not exposed by the API.
USAGE_VIEW = """
CREATE VIEW monthly_outbound_message_counts AS
SELECT
    organization_id,
    to_char(sent_at AT TIME ZONE 'America/Santo_Domingo', 'YYYY-MM') AS month,
    CASE WHEN content_type = 'template' THEN 'template' ELSE 'session' END AS delivery,
    kind,
    count(*) AS messages
FROM messages
WHERE channel = 'whatsapp'
  AND direction = 'outbound'
  AND status IN ('sent', 'delivered', 'read')
  AND sent_at IS NOT NULL
GROUP BY 1, 2, 3, 4
"""


